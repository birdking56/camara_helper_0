# prepare_mem_model.ps1
#
# The vendor DDR3 bench model (ipcore/ddr3_test/example_design/bench/mem/ddr3.v)
# starts with
#
#     `include "../../example_design/bench/mem/ddr3_parameters.vh"
#
# which is a path relative to the *working directory* used by the vendor's own
# Modelsim flow (they run vlog from ipcore/ddr3_test/sim/modelsim). Compiling the
# file from anywhere else fails with "Cannot find `include file".
#
# Rather than running our whole simulation inside the vendor directory (which
# would drop a work library there), this script stages a self-contained copy in
# sim/ddr3_sim/mem/ with the include rewritten to a plain filename. The vendor
# originals are never modified.
#
# Run it once, or again whenever the vendor IP is regenerated:
#     powershell -NoProfile -File sim\ddr3_sim\prepare_mem_model.ps1

$ErrorActionPreference = "Stop"

$root = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$src  = Join-Path $root "ipcore\ddr3_test\example_design\bench\mem"
$dst  = Join-Path $PSScriptRoot "mem"

New-Item -ItemType Directory -Force -Path $dst | Out-Null

$paramSrc = Join-Path $src "ddr3_parameters.vh"
$memSrc   = Join-Path $src "ddr3.v"

if (-not (Test-Path $paramSrc)) { throw "missing $paramSrc" }
if (-not (Test-Path $memSrc))   { throw "missing $memSrc" }

Copy-Item $paramSrc (Join-Path $dst "ddr3_parameters.vh") -Force

$mem = Get-Content $memSrc -Raw
$patched = $mem -replace '`include\s+"[^"]*ddr3_parameters\.vh"', '`include "ddr3_parameters.vh"'
if ($patched -eq $mem) {
    Write-Warning "the include line was not found; the copy may not compile"
}

$header = @'
// ---------------------------------------------------------------------------
// STAGED COPY - do not edit, do not synthesise.
// Generated by sim/ddr3_sim/prepare_mem_model.ps1 from
//   ipcore/ddr3_test/example_design/bench/mem/ddr3.v
// The only change is the `include line, rewritten to a plain filename so the
// model compiles from any working directory with +incdir pointing here.
// ---------------------------------------------------------------------------
'@

Set-Content -Path (Join-Path $dst "ddr3.v") -Value (($header.TrimEnd()) + "`r`n" + $patched) -Encoding ascii
Write-Host "staged DDR3 bench model into $dst"
Get-ChildItem $dst | Select-Object Name, Length | Format-Table -AutoSize
